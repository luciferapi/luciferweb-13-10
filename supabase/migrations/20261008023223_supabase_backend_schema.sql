create or replace function public.auth_resend_pending_registration_otp(
  p_email text,
  p_otp_hash text,
  p_otp_duration_seconds integer,
  p_resend_seconds integer,
  p_max_attempts integer
)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  v_pending public.auth_pending_registrations%rowtype;
  v_now timestamptz := now();
begin
  select * into v_pending
  from public.auth_pending_registrations as pending
  where pending.email = lower(trim(p_email))
  for update;

  if not found then
    return jsonb_build_object('status', 'missing');
  end if;

  if v_pending.registration_expires_at <= v_now
     or v_pending.attempts >= p_max_attempts then
    delete from public.auth_pending_registrations as pending
    where pending.email = v_pending.email;
    return jsonb_build_object(
      'status', 'expired',
      'auth_user_id', v_pending.auth_user_id
    );
  end if;

  if v_pending.resend_after > v_now then
    return jsonb_build_object(
      'status', 'cooldown',
      'retry_after_seconds',
      ceil(extract(epoch from (v_pending.resend_after - v_now)))::integer
    );
  end if;

  update public.auth_pending_registrations as pending
  set otp_hash = p_otp_hash,
      expires_at = v_now + make_interval(secs => p_otp_duration_seconds),
      resend_after = v_now + make_interval(secs => p_resend_seconds),
      attempts = 0
  where pending.email = v_pending.email;

  return jsonb_build_object('status', 'sent', 'name', v_pending.name);
end;
$$;

create or replace function public.auth_verify_email_registration(
  p_email text,
  p_otp_hash text,
  p_profile_id uuid,
  p_session_token_hash text,
  p_session_expires_at timestamptz,
  p_public_uid text,
  p_max_attempts integer
)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  v_pending public.auth_pending_registrations%rowtype;
  v_user public.auth_users%rowtype;
  v_now timestamptz := now();
begin
  select * into v_pending
  from public.auth_pending_registrations as pending
  where pending.email = lower(trim(p_email))
  for update;

  if not found then
    return jsonb_build_object('status', 'missing');
  end if;

  if v_pending.registration_expires_at <= v_now then
    delete from public.auth_pending_registrations as pending
    where pending.email = v_pending.email;
    return jsonb_build_object(
      'status', 'expired',
      'discard_auth_user', true,
      'auth_user_id', v_pending.auth_user_id
    );
  end if;

  if v_pending.expires_at <= v_now then
    return jsonb_build_object('status', 'expired');
  end if;

  if v_pending.attempts >= p_max_attempts then
    delete from public.auth_pending_registrations as pending
    where pending.email = v_pending.email;
    return jsonb_build_object(
      'status', 'attempts-exceeded',
      'discard_auth_user', true,
      'auth_user_id', v_pending.auth_user_id
    );
  end if;

  if v_pending.otp_hash <> p_otp_hash then
    update public.auth_pending_registrations as pending
    set attempts = pending.attempts + 1
    where pending.email = v_pending.email
    returning * into v_pending;
    if v_pending.attempts >= p_max_attempts then
      delete from public.auth_pending_registrations as pending
      where pending.email = v_pending.email;
      return jsonb_build_object(
        'status', 'attempts-exceeded',
        'discard_auth_user', true,
        'auth_user_id', v_pending.auth_user_id
      );
    end if;
    return jsonb_build_object('status', 'invalid');
  end if;

  if exists (
    select 1 from public.auth_users as users
    where users.email = v_pending.email
  ) then
    delete from public.auth_pending_registrations as pending
    where pending.email = v_pending.email;
    return jsonb_build_object(
      'status', 'already-registered',
      'discard_auth_user', true,
      'auth_user_id', v_pending.auth_user_id
    );
  end if;

  if v_pending.signup_ip_hash is not null and exists (
    select 1 from public.auth_users as users
    where users.signup_ip_hash = v_pending.signup_ip_hash
  ) then
    delete from public.auth_pending_registrations as pending
    where pending.email = v_pending.email;
    return jsonb_build_object(
      'status', 'ip-already-registered',
      'discard_auth_user', true,
      'auth_user_id', v_pending.auth_user_id
    );
  end if;

  insert into public.auth_users (
    id, public_uid, name, email, date_of_birth, signup_ip_hash
  ) values (
    p_profile_id, p_public_uid, v_pending.name, v_pending.email,
    v_pending.date_of_birth, v_pending.signup_ip_hash
  )
  returning * into v_user;

  insert into public.auth_identities (provider, provider_user_id, user_id)
  values ('supabase', v_pending.auth_user_id::text, v_user.id);
  insert into public.auth_sessions (token_hash, user_id, expires_at, auth_method)
  values (p_session_token_hash, v_user.id, p_session_expires_at, 'email_otp');

  if v_pending.referral_code is not null then
    insert into public.referrals (id, referrer_id, referee_id)
    select gen_random_uuid(), profile.user_id, v_user.id
    from public.referral_profiles as profile
    where profile.referral_code = v_pending.referral_code
      and profile.user_id <> v_user.id
    on conflict (referee_id) do nothing;
  end if;

  delete from public.auth_pending_registrations as pending
  where pending.email = v_pending.email;

  return jsonb_build_object('status', 'verified', 'user', to_jsonb(v_user));
exception
  when unique_violation then
    if exists (
      select 1 from public.auth_users as users
      where users.signup_ip_hash = v_pending.signup_ip_hash
    ) then
      delete from public.auth_pending_registrations as pending
      where pending.email = v_pending.email;
      return jsonb_build_object(
        'status', 'ip-already-registered',
        'discard_auth_user', true,
        'auth_user_id', v_pending.auth_user_id
      );
    end if;
    raise;
end;
$$;

