  p_otp_hash text,
  p_expires_at timestamptz,
  p_resend_after timestamptz
)
returns jsonb
language plpgsql
set search_path = ''
as $$
begin
  if not exists (
    select 1 from public.auth_users as users
    where users.id = p_user_id and users.email = lower(trim(p_email))
  ) then
    return jsonb_build_object('status', 'missing');
  end if;

