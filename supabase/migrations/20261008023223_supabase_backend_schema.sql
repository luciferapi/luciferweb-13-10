create or replace function public.auth_update_user_profile(
  p_user_id uuid,
  p_name text,
  p_date_of_birth date,
  p_telegram_username text,
  p_x_username text,
  p_update_name boolean,
  p_update_date_of_birth boolean,
  p_update_telegram_username boolean,
  p_update_x_username boolean
)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  v_user public.auth_users%rowtype;
  v_name_changed boolean;
  v_dob_changed boolean;
begin
  select * into v_user
  from public.auth_users as users
  where users.id = p_user_id
  for update;
  if not found then
    return jsonb_build_object('status', 'missing');
  end if;

  v_name_changed := p_update_name and p_name is distinct from v_user.name;
  v_dob_changed := p_update_date_of_birth and p_date_of_birth is distinct from v_user.date_of_birth;
  if v_name_changed and v_user.name_edit_used then
    return jsonb_build_object('status', 'name-already-edited');
  end if;
  if v_dob_changed and v_user.date_of_birth_edit_used then
    return jsonb_build_object('status', 'date-of-birth-already-edited');
  end if;
  if not v_name_changed and not v_dob_changed
     and not p_update_telegram_username and not p_update_x_username then
    return jsonb_build_object('status', 'unchanged');
  end if;

  update public.auth_users as users
  set name = case when v_name_changed then p_name else users.name end,
      name_edit_used = users.name_edit_used or v_name_changed,
      date_of_birth = case when v_dob_changed then p_date_of_birth else users.date_of_birth end,
      date_of_birth_edit_used = users.date_of_birth_edit_used or v_dob_changed,
      telegram_username = case when p_update_telegram_username then p_telegram_username else users.telegram_username end,
      x_username = case when p_update_x_username then p_x_username else users.x_username end
  where users.id = p_user_id;

  return jsonb_build_object('status', 'updated');
end;
$$;

create or replace function public.auth_create_password_reset_token(
  p_email text,
  p_token_hash text,
  p_expires_at timestamptz
)
returns jsonb
language plpgsql
set search_path = ''
as $$
