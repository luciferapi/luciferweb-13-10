create or replace function public.auth_claim_password_reset_token(
  p_token_hash text,
  p_claim_token uuid,
  p_claim_expires_at timestamptz
)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  v_reset public.auth_password_resets%rowtype;
  v_auth_user_id text;
begin
  select * into v_reset
  from public.auth_password_resets as resets
  where resets.token_hash = p_token_hash
  for update;
  if not found or v_reset.expires_at <= now() then
    delete from public.auth_password_resets as resets
    where resets.token_hash = p_token_hash;
    return jsonb_build_object('status', 'missing');
  end if;
  if v_reset.claim_token is not null and v_reset.claim_expires_at > now() then
    return jsonb_build_object('status', 'claimed');
  end if;

  select identities.provider_user_id into v_auth_user_id
  from public.auth_identities as identities
  where identities.user_id = v_reset.user_id
    and identities.provider = 'supabase'
  limit 1;
  if v_auth_user_id is null then
    delete from public.auth_password_resets as resets
    where resets.token_hash = p_token_hash;
    return jsonb_build_object('status', 'missing');
  end if;

  update public.auth_password_resets as resets
  set claim_token = p_claim_token,
      claim_expires_at = p_claim_expires_at
  where resets.token_hash = p_token_hash;
  return jsonb_build_object('status', 'claimed', 'auth_user_id', v_auth_user_id);
end;
$$;

create or replace function public.auth_complete_password_reset(
  p_token_hash text,
  p_claim_token uuid,
  p_success boolean
)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  v_user_id uuid;
begin
  select resets.user_id into v_user_id
  from public.auth_password_resets as resets
  where resets.token_hash = p_token_hash
    and resets.claim_token = p_claim_token
    and resets.claim_expires_at > now()
  for update;
  if not found then
    return jsonb_build_object('status', 'missing');
  end if;

  if p_success then
    delete from public.auth_sessions as sessions
    where sessions.user_id = v_user_id;
    delete from public.auth_password_resets as resets
    where resets.user_id = v_user_id;
    return jsonb_build_object('status', 'completed');
  end if;

  update public.auth_password_resets as resets
  set claim_token = null, claim_expires_at = null
  where resets.token_hash = p_token_hash;
  return jsonb_build_object('status', 'released');
end;
$$;

create or replace function public.mark_wallet_deposit_paid(
