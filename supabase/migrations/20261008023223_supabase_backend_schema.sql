create or replace function public.auth_verify_owner_login_otp(
  p_email text,
  p_otp_hash text,
  p_session_token_hash text,
  p_session_expires_at timestamptz,
  p_max_attempts integer
)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  v_otp public.auth_owner_login_otps%rowtype;
  v_user public.auth_users%rowtype;
begin
  select * into v_otp
  from public.auth_owner_login_otps as otps
  where otps.email = lower(trim(p_email))
  for update;

  if not found then
    return jsonb_build_object('status', 'missing');
  end if;

  if v_otp.expires_at <= now() then
    delete from public.auth_owner_login_otps as otps
    where otps.email = v_otp.email;
    return jsonb_build_object('status', 'expired');
  end if;

  if v_otp.attempts >= p_max_attempts then
    delete from public.auth_owner_login_otps as otps
    where otps.email = v_otp.email;
    return jsonb_build_object('status', 'attempts-exceeded');
  end if;

  if v_otp.otp_hash <> p_otp_hash then
    update public.auth_owner_login_otps as otps
    set attempts = otps.attempts + 1
    where otps.email = v_otp.email
    returning * into v_otp;
    if v_otp.attempts >= p_max_attempts then
      delete from public.auth_owner_login_otps as otps
      where otps.email = v_otp.email;
      return jsonb_build_object('status', 'attempts-exceeded');
    end if;
    return jsonb_build_object('status', 'invalid');
  end if;

  select * into v_user
  from public.auth_users as users
  where users.id = v_otp.user_id;
  if not found then
    delete from public.auth_owner_login_otps as otps
    where otps.email = v_otp.email;
    return jsonb_build_object('status', 'missing');
  end if;

  insert into public.auth_sessions (token_hash, user_id, expires_at, auth_method)
  values (p_session_token_hash, v_user.id, p_session_expires_at, 'email_otp');
  delete from public.auth_owner_login_otps as otps
  where otps.email = v_otp.email;

  return jsonb_build_object('status', 'verified', 'user', to_jsonb(v_user));
end;
$$;

create or replace function public.auth_get_or_create_oauth_user(
  p_provider text,
  p_provider_user_id text,
  p_name text,
  p_email text,
  p_email_verified boolean,
  p_allow_create boolean,
  p_date_of_birth date,
  p_referral_code text,
  p_signup_ip_hash text,
  p_public_uid text
)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  v_user public.auth_users%rowtype;
  v_constraint text;
begin
  select users.* into v_user
  from public.auth_identities as identities
  join public.auth_users as users on users.id = identities.user_id
  where identities.provider = p_provider
    and identities.provider_user_id = p_provider_user_id
  for update of users;

  if found then
    return jsonb_build_object('status', 'found', 'user', to_jsonb(v_user));
  end if;

  if p_email is not null and p_email_verified then
    select * into v_user
    from public.auth_users as users
    where users.email = lower(trim(p_email))
    for update;
    if found then
      insert into public.auth_identities (provider, provider_user_id, user_id)
      values (p_provider, p_provider_user_id, v_user.id);
      return jsonb_build_object('status', 'found', 'user', to_jsonb(v_user));
    end if;
  end if;

  if not p_allow_create then
    return jsonb_build_object('status', 'signup-required');
  end if;
  if p_signup_ip_hash is null then
    return jsonb_build_object('status', 'ip-already-registered');
  end if;
  if exists (
    select 1 from public.auth_users as users
    where users.signup_ip_hash = p_signup_ip_hash
  ) then
    return jsonb_build_object('status', 'ip-already-registered');
  end if;

  insert into public.auth_users (
    id, public_uid, name, email, date_of_birth, signup_ip_hash
  ) values (
    gen_random_uuid(), p_public_uid, p_name,
    case when p_email_verified then lower(trim(p_email)) else null end,
    p_date_of_birth, p_signup_ip_hash
  )
  returning * into v_user;

  insert into public.auth_identities (provider, provider_user_id, user_id)
  values (p_provider, p_provider_user_id, v_user.id);

  if p_referral_code is not null then
    insert into public.referrals (id, referrer_id, referee_id)
    select gen_random_uuid(), profile.user_id, v_user.id
    from public.referral_profiles as profile
    where profile.referral_code = upper(trim(p_referral_code))
      and profile.user_id <> v_user.id
    on conflict (referee_id) do nothing;
  end if;

  return jsonb_build_object('status', 'created', 'user', to_jsonb(v_user));
exception
  when unique_violation then
    get stacked diagnostics v_constraint = constraint_name;
    if v_constraint = 'auth_users_signup_ip_hash_key' then
      return jsonb_build_object('status', 'ip-already-registered');
    end if;
    raise;
