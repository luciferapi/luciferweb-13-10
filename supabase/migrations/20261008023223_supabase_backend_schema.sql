create or replace function public.create_wallet_withdrawal_request(
  p_request_id uuid,
  p_withdrawal_id text,
  p_user_id uuid,
  p_amount_paise bigint,
  p_method_type text,
  p_payout_destination text,
  p_request_date date
)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  v_request_count integer;
  v_available_paise bigint;
begin
  perform 1
  from public.auth_users as users
  where users.id = p_user_id
  for update;
  if not found then
    return jsonb_build_object('success', false, 'error_code', 'insufficient_balance');
  end if;

  select count(*)::integer into v_request_count
  from public.wallet_withdrawal_requests as withdrawals
  where withdrawals.user_id = p_user_id
    and withdrawals.request_date = p_request_date;
  if v_request_count >= 4 then
    return jsonb_build_object('success', false, 'error_code', 'daily_limit');
  end if;

  select (
    coalesce((
      select sum(deposits.amount_paise)
      from public.wallet_deposits as deposits
      where deposits.user_id = p_user_id and deposits.status = 'paid'
    ), 0)
    - coalesce((
      select sum(withdrawals.amount_paise)
      from public.wallet_withdrawal_requests as withdrawals
      where withdrawals.user_id = p_user_id and withdrawals.status in ('paid', 'pending')
    ), 0)
  )::bigint into v_available_paise;
  if p_amount_paise < 5000 or p_amount_paise > 150000
     or p_amount_paise > v_available_paise then
    return jsonb_build_object('success', false, 'error_code', 'insufficient_balance');
  end if;

  insert into public.wallet_withdrawal_requests (
    request_id, withdrawal_id, user_id, amount_paise, method_type,
    payout_destination, request_date, status
  ) values (
    p_request_id, p_withdrawal_id, p_user_id, p_amount_paise, p_method_type,
    p_payout_destination, p_request_date, 'pending'
  );

  return jsonb_build_object(
    'success', true,
    'withdrawal_id', p_withdrawal_id,
    'remaining_requests', 4 - v_request_count - 1
  );
end;
$$;

create or replace function public.get_user_referral_tree(p_user_id uuid)
returns table (
  id uuid,
  referrer_id uuid,
  referee_id uuid,
  name text,
  email text,
  status text,
  status_reason text,
  depth integer,
  created_at timestamptz,
  signup_at timestamptz
)
language sql
stable
set search_path = ''
as $$
  with recursive referral_tree as (
    select referrals.id, referrals.referrer_id, referrals.referee_id,
           referrals.status, referrals.status_reason, referrals.created_at,
           0 as depth, array[referrals.referrer_id, referrals.referee_id] as path
    from public.referrals as referrals
    where referrals.referrer_id = p_user_id
    union all
    select child.id, child.referrer_id, child.referee_id,
           child.status, child.status_reason, child.created_at,
           parent.depth + 1, parent.path || child.referee_id
    from public.referrals as child
    join referral_tree as parent on child.referrer_id = parent.referee_id
    where parent.depth < 9
      and not child.referee_id = any(parent.path)
  )
  select tree.id, tree.referrer_id, tree.referee_id, users.name, users.email,
         tree.status, tree.status_reason, tree.depth, tree.created_at,
         users.created_at as signup_at
  from referral_tree as tree
  join public.auth_users as users on users.id = tree.referee_id
  order by tree.depth, tree.created_at desc;
$$;

