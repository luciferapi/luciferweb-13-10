create or replace function public.owner_invite_admin(
  p_actor_user_id uuid,
  p_email text
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user public.auth_users%rowtype;
begin
  if not exists (
    select 1 from public.owner_admins as admins
    where admins.user_id = p_actor_user_id
  ) then
    return 'unauthorized';
  end if;

  select * into v_user
  from public.auth_users as users
  where lower(users.email) = lower(trim(p_email));

  if not found then
    return 'user_not_found';
  end if;
  if v_user.is_blocked then
    return 'user_blocked';
  end if;

  insert into public.owner_admins (user_id, added_by)
  values (v_user.id, p_actor_user_id)
  on conflict (user_id) do nothing;

  if not found then
    return 'already_admin';
  end if;

  insert into public.owner_audit_logs (actor_user_id, action, subject_user_id)
  values (p_actor_user_id, 'admin.invited', v_user.id);
  return 'invited';
end;
$$;

create or replace function public.owner_revoke_admin(
  p_actor_user_id uuid,
  p_target_user_id uuid
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_target_email text;
begin
  if not exists (
    select 1 from public.owner_admins as admins
    where admins.user_id = p_actor_user_id
  ) then
    return 'unauthorized';
  end if;
  if p_actor_user_id = p_target_user_id then
    return 'cannot_revoke_self';
  end if;

  select users.email into v_target_email
  from public.auth_users as users
  where users.id = p_target_user_id;
  if lower(v_target_email) = 'kspgpraveen157@gmail.com' then
    return 'primary_admin';
  end if;

  delete from public.owner_admins as admins
  where admins.user_id = p_target_user_id;
  if not found then
    return 'not_admin';
  end if;

  delete from public.auth_owner_login_otps as otps
  where otps.user_id = p_target_user_id;
  delete from public.auth_sessions as sessions
  where sessions.user_id = p_target_user_id;
  insert into public.owner_audit_logs (actor_user_id, action, subject_user_id)
  values (p_actor_user_id, 'admin.revoked', p_target_user_id);
  return 'revoked';
end;
$$;

create or replace function public.owner_set_user_block_status(
  p_actor_user_id uuid,
  p_target_user_id uuid,
  p_is_blocked boolean
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_target_email text;
  v_previous_status boolean;
begin
  if not exists (
    select 1 from public.owner_admins as admins
    where admins.user_id = p_actor_user_id
  ) then
    return 'unauthorized';
  end if;

  select users.email, users.is_blocked
  into v_target_email, v_previous_status
  from public.auth_users as users
  where users.id = p_target_user_id
  for update;
  if not found then
    return 'user_not_found';
  end if;
  if lower(v_target_email) = 'kspgpraveen157@gmail.com' then
    return 'primary_admin';
  end if;
  if exists (
    select 1 from public.owner_admins as admins
    where admins.user_id = p_target_user_id
  ) then
    return 'admin_must_be_revoked_first';
  end if;
  if v_previous_status = p_is_blocked then
    return 'unchanged';
  end if;

  update public.auth_users as users
  set is_blocked = p_is_blocked,
      blocked_at = case when p_is_blocked then pg_catalog.now() else null end
  where users.id = p_target_user_id;

  if p_is_blocked then
    delete from public.auth_sessions as sessions
    where sessions.user_id = p_target_user_id;
  end if;

  insert into public.owner_audit_logs (actor_user_id, action, subject_user_id, details)
  values (
    p_actor_user_id,
    case when p_is_blocked then 'user.blocked' else 'user.unblocked' end,
    p_target_user_id,
    pg_catalog.jsonb_build_object('blocked', p_is_blocked)
  );
  return 'updated';
end;
$$;

create or replace function public.owner_set_withdrawal_status(
  p_actor_user_id uuid,
  p_request_id uuid,
  p_status text,
  p_external_payment_confirmed boolean
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid;
begin
  if not exists (
    select 1 from public.owner_admins as admins
    where admins.user_id = p_actor_user_id
  ) then
    return 'unauthorized';
  end if;
  if p_status not in ('paid', 'rejected') then
    return 'invalid_status';
  end if;
  if p_status = 'paid' and not p_external_payment_confirmed then
    return 'payment_confirmation_required';
  end if;

  update public.wallet_withdrawal_requests as withdrawals
  set status = p_status,
      updated_at = pg_catalog.now()
  where withdrawals.request_id = p_request_id
    and withdrawals.status = 'pending'
  returning withdrawals.user_id into v_user_id;
  if not found then
    return 'not_pending';
  end if;

  insert into public.owner_audit_logs (actor_user_id, action, subject_user_id, details)
  values (
    p_actor_user_id,
    case when p_status = 'paid' then 'withdrawal.marked_paid' else 'withdrawal.rejected' end,
    v_user_id,
    pg_catalog.jsonb_build_object(
      'requestId', p_request_id,
      'externalPaymentConfirmed', p_external_payment_confirmed
    )
  );
  return 'updated';
end;
$$;

create or replace function public.owner_wallet_summary()
returns table (
  total_users bigint,
  active_users bigint,
  blocked_users bigint,
  wallet_balance_paise bigint,
  paid_deposits_paise bigint,
  pending_withdrawals_paise bigint,
  paid_withdrawals_paise bigint
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    (select count(*) from public.auth_users),
    (select count(*) from public.auth_users where not is_blocked),
    (select count(*) from public.auth_users where is_blocked),
    coalesce((select sum(amount_paise) from public.wallet_deposits where status = 'paid'), 0)
      - coalesce((select sum(amount_paise) from public.wallet_withdrawal_requests where status in ('paid', 'pending')), 0),
    coalesce((select sum(amount_paise) from public.wallet_deposits where status = 'paid'), 0),
    coalesce((select sum(amount_paise) from public.wallet_withdrawal_requests where status = 'pending'), 0),
    coalesce((select sum(amount_paise) from public.wallet_withdrawal_requests where status = 'paid'), 0);
$$;

